/* JATAYU simple console — pure, testable data handling.
   Loaded as a classic script so the page also works when opened from disk (file://).
   Every function here only reshapes what the backend already returned: nothing is
   invented when a value is missing. */

function numberText(value, decimals) {
  if (typeof value !== 'number' || !Number.isFinite(value)) return '—';
  return value.toFixed(decimals || 0);
}

/* Source labels must never let simulated or demo data look like live hardware. */
function provenance(status) {
  status = status || {};
  const source = status.source;
  if (source === 'demo') return { label: 'DEMO OVERRIDE', tone: 'amber', description: 'Synthetic RF override from the backend demo mode. Other readings may be cached, so treat this screen as demonstration data rather than live sensor evidence.' };
  if (source === 'simulated' || source === 'simulation') return { label: 'SIMULATED', tone: 'amber', description: 'Values generated by the JATAYU backend simulator. No live hardware is connected to this preview.' };
  if ((source === 'live' || source === 'serial') && (status.arduino_link?.simulated || status.csi_link?.kind === 'simulation')) return { label: 'MIXED SOURCES', tone: 'amber', description: 'At least one input path is simulated. Do not treat every reading on this screen as live.' };
  if (source === 'live' || source === 'serial') return { label: 'LIVE INPUT', tone: 'green', description: 'Reading from your JATAYU backend. Check device freshness and signal quality before reviewing an observation.' };
  return { label: 'SOURCE UNKNOWN', tone: 'muted', description: 'Waiting for the backend to identify the input source. No sample values are being shown.' };
}

/* Only finite [seconds, value] pairs become trace points. */
function tracePoints(telemetry) {
  telemetry = telemetry || {};
  if (telemetry.valid === false || !Array.isArray(telemetry.waveform)) return [];
  return telemetry.waveform.filter(point =>
    Array.isArray(point) && point.length >= 2 && Number.isFinite(point[0]) && Number.isFinite(point[1]));
}

/* Reachability of the page's own polling, separate from sensor freshness. */
function connectionState(input) {
  input = input || {};
  const now = typeof input.now === 'number' ? input.now : Date.now();
  if (input.paused) return 'paused';
  if (input.failed) return 'disconnected';
  if (!input.lastSuccess) return 'connecting';
  return now - input.lastSuccess > 6000 ? 'stale' : 'connected';
}

/* Accept an origin only: no paths, credentials, or non-HTTP schemes. */
function backendURL(value) {
  const url = new URL(String(value).trim());
  if (!['http:', 'https:'].includes(url.protocol) || url.username || url.password || url.pathname !== '/' || url.search || url.hash) {
    throw new Error('Enter an HTTP or HTTPS origin, such as http://192.168.1.22:8000 — no path or credentials.');
  }
  return url.origin;
}

/* GET-only reader for the existing API. */
async function readResource(base, path, signal) {
  const timeout = AbortSignal.timeout(4000);
  const response = await fetch(base + path, {
    method: 'GET',
    cache: 'no-store',
    credentials: 'omit',
    signal: signal ? AbortSignal.any([timeout, signal]) : timeout
  });
  if (!response.ok) throw new Error(path + ': HTTP ' + response.status);
  return response.json();
}
